const assert = require('node:assert/strict');
const { create, STORAGE } = require('../assets/child-progress.js');
const values = new Map();
const storage = { getItem: key => values.get(key), setItem: (key, value) => values.set(key, value) };
const saved = () => JSON.parse(values.get(STORAGE));
const record = (key, domain, correct, total, presentation = 'advanced') => ({ key, domain, correct, total, presentation, title: 'ولد يأكل', entity: key.startsWith('w:') ? 'word' : 'sentence' });
const assessment = (id, records, extra = {}) => ({ id, kind: 'assessment', records, date: '2026-10-18T09:00:00Z', ...extra });

let p = create(storage);
p.signIn('  علي  ');
const childId = p.active().id;
assert.equal(p.active().name, 'علي');
assert.equal(p.workspace(), null);
p.saveWorkspace({ isAdvancedMode: true, row1Slots: [] });
p.saveDraft({ id: 'resumable', phase: 'repetition', index: 3 });
assert.equal(saved().children.find(child => child.id === childId).senb.draft.index, 3);
p.saveLesson({ text: 'ماما وبابا، خلّونا نلعب سوا.' });

const key = 's:2/1/1';
p.logSession(assessment('practice', [record(key, 'receptive', 5, 5)], { kind: 'practice' }));
p.logSession(assessment('partial', [record(key, 'receptive', 5, 5)], { partial: true }));
assert.equal(p.learned(key, 'receptive'), false, 'Practice and interrupted assessments never earn mastery');
p.logSession(assessment('below', [record(key, 'receptive', 3, 4)]));
assert.equal(p.learned(key, 'receptive'), false, 'Mastery requires at least 80%');
p.logSession(assessment('threshold', [record(key, 'receptive', 3, 4), record(key, 'receptive', 1, 1, 'slots')]));
assert.equal(p.learned(key, 'receptive'), true, 'Aggregate both image presentations for this sentence/domain');
assert.equal(p.learned(key, 'expressive'), false, 'Domains must remain independent');
p.logSession(assessment('later-lower', [record(key, 'receptive', 0, 1)]));
assert.equal(p.learned(key, 'receptive'), true, 'Attained mastery remains visible after a later difficult trial');
p.logSession(assessment('partial', [record(key, 'expressive', 4, 5)]));
assert.equal(p.learned(key, 'expressive'), true, 'A completed session may replace its partial draft');
assert.equal(p.sessions().filter(session => session.id === 'partial').length, 1, 'Resuming must not duplicate the session');
p.logSession(assessment('partial', [record(key, 'expressive', 0, 5)]));
assert.equal(p.sessions().find(session => session.id === 'partial').records[0].correct, 4, 'A duplicate completed id cannot replace final evidence');
p.logSession(assessment('word', [record('w:2/1', 'expressive', 4, 5, 'slots')]));
assert.equal(p.learned('w:2/1', 'expressive'), true);
assert.equal(p.learned('w:2/1', 'receptive'), false);
assert.equal(p.learned(key, 'unknown'), false);

const exported = p.sessions(); exported[0].records[0].correct = 0;
assert.equal(p.sessions()[0].records[0].correct, 5, 'Report consumers must not mutate saved evidence');
const otherTab = create(storage);
p.saveDraft({ id: 'updated-draft', index: 7 });
otherTab.saveLesson({ text: 'تمرين جديد' });
assert.equal(saved().children.find(child => child.id === childId).senb.draft.index, 7, 'A lesson save must retain another tab’s draft');

p = create(storage);
assert.equal(p.active().id, childId, 'The learner stays active after reopening');
assert.equal(p.learned(key, 'expressive'), true);
p.saveWorkspace({ row1Slots: [] });
assert.deepEqual(p.workspace(), { row1Slots: [] }, 'An explicitly empty board is a saved workspace');
p.saveDraft(null); assert.equal(p.draft(), null);
let warned = false;
const unavailable = create({ getItem: () => '{bad json', setItem: () => { throw Error('full'); } }, () => { warned = true; });
unavailable.signIn('ليان');
assert.equal(unavailable.active().name, 'ليان');
assert.equal(unavailable.storageOK(), false);
assert.equal(warned, true);
console.log('SENB device progress, 80% mastery, resumable evidence, and concurrent app saves passed.');
